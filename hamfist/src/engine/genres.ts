const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

// Rows are grouped by "#Section" markers, which become the browser groups.
export const GENRES: Genre[] = [];
{
  let section = "Pop";
  for (const row of ROWS) {
    if (typeof row === "string") {
      section = row.slice(1);
      continue;
    }
    const [name, family, bpm, o] = row;
    const f = famIndex.get(family);
    if (!f) throw new Error(`Unknown family "${family}" for genre "${name}"`);
    const { id: _id, group: _group, ...style } = f;
    GENRES.push({ ...style, ...(bpm ? { bpm } : {}), ...(o ?? {}), id: slug(name), name, family, group: section });
  }
}

export const GROUPS: string[] = [...new Set(GENRES.map((g) => g.group))];

const genreIndex = new Map(GENRES.map((g) => [g.id, g]));

export function getGenre(id: string): Genre {
  return genreIndex.get(id) ?? GENRES[0];
}
