// Genre database. A few dozen "families" carry the full musical recipe
// (scale, progressions, groove, instrumentation); several hundred genres
// inherit from a family and override whatever makes them distinct.
import type { ArpShape } from "./patterns";

export interface Style {
  bpm: number;
  meter: string;
  /** 0-0.6: how far odd sixteenth steps are pushed late. */
  swing: number;
  scale: string;
  /** Progressions as space separated chord tokens, see theory.parseToken. */
  progs: string[];
  /** Bars per chord. */
  hr: number;
  drums: string;
  bass: string;
  comp: string;
  arp: [ArpShape, number];
  kit: string;
  lead: string;
  chords: string;
  bassI: string;
  pad: string;
  arpI: string;
}

export interface Family extends Style {
  id: string;
  group: string;
}

export interface Genre extends Style {
  id: string;
  name: string;
  family: string;
  group: string;
}

